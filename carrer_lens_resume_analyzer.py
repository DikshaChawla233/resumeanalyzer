import ast
import numpy as np

def extract_average_result(x):
    # Convert string like "['3.84']" into ['3.84']
    if isinstance(x, str):
        try:
            x = ast.literal_eval(x)
        except:
            return 0

    if not isinstance(x, list):
        return 0

    values = []

    for value in x:
        try:
            if value is not None and str(value).upper() != 'N/A':
                values.append(float(value))
        except:
            continue

    return np.mean(values) if values else 0


