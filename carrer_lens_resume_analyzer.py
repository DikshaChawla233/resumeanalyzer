df.columns = df.columns.str.replace("\ufeff", "", regex=False).str.strip()

print("Job title column exists:", "job_position_name" in df.columns)
print("\nSample job titles:")
print(df["job_position_name"].dropna().unique()[:15])

print("\nSample required skills:")
print(df["skills_required"].dropna().head(3).tolist())

print("\nSample experience requirements:")
print(df["experiencere_requirement"].dropna().unique()[:5])

# Inspect one dataset record without changing the dataset

row = df.iloc[0]

columns_to_check = [
    "job_position_name",
    "skills",
    "skills_required",
    "related_skils_in_job",
    "degree_names",
    "major_field_of_studies",
    "experiencere_requirement",
    "matched_score"
]

for col in columns_to_check:
    if col in df.columns:
        print(f"\n--- {col} ---")
        print(row[col])

# Check the dataset's job records and missing values

print("Total records:", len(df))
print("Unique job titles:", df["job_position_name"].nunique())

print("\nMissing values in important columns:")
for col in [
    "skills",
    "skills_required",
    "educationaL_requirements",
    "experiencere_requirement",
    "matched_score"
]:
    print(f"{col}: {df[col].isna().sum()}")

print("\nAvailable jobs with their requirements:")

job_summary = (
    df.groupby("job_position_name", dropna=True)
      .agg(
          records=("matched_score", "size"),
          education=("educationaL_requirements", "first"),
          experience=("experiencere_requirement", "first"),
          required_skills=("skills_required", "first")
      )
      .reset_index()
)

print(job_summary.head(10).to_string(index=False))

from pathlib import Path
import shutil

# Create a backup folder without changing your existing files
backup_dir = Path("career_lens_backup")
backup_dir.mkdir(exist_ok=True)

files_to_backup = [
    "main.py",
    "frontend/index.html",
    "frontend/style.css",
    "frontend/script.js"
]

for filename in files_to_backup:
    source = Path(filename)

    if source.exists():
        destination = backup_dir / source.name
        shutil.copy2(source, destination)
        print(f"Backed up: {filename}")
    else:
        print(f"Not found yet: {filename}")

print("\nBackup step finished.")

