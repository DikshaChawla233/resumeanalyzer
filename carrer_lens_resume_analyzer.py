import joblib
import pandas as pd
import numpy as np
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from typing import Dict, Any

class CareerLensPredictor:
    def __init__(self, model_path="career_lens_model.pkl",
                 scaler_path="career_lens_scaler.pkl",
                 features_path="career_lens_features.pkl"):
        self.model = joblib.load(model_path)
        self.scaler = joblib.load(scaler_path)
        self.expected_features = joblib.load(features_path)

    def preprocess_input(self, input_data: dict) -> pd.DataFrame:
        df_raw = pd.DataFrame([input_data])
        df_encoded = pd.get_dummies(df_raw)
        df_aligned = df_encoded.reindex(columns=self.expected_features, fill_value=0)
        scaled_array = self.scaler.transform(df_aligned)
        return scaled_array

    def predict(self, input_data: dict) -> float:
        scaled_input = self.preprocess_input(input_data)
        prediction = self.model.predict(scaled_input)[0]
        return float(prediction)

app = FastAPI(title="Career Lens API", version="1.0")
